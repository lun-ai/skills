"""Shared parsing for the paper-library scripts. Standard library only."""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

FIELD = re.compile(r"^- \*\*(.+?):\*\*\s*(.*)$")
STEM = re.compile(r"^[a-z0-9-]+_[a-z0-9.-]+_[a-z0-9.-]+$")
DATE = re.compile(r"^\d{4}(-\d{2}){0,2}$")
REQUIRED_FIELDS = ["Authors", "Date", "Source", "Topic", "Priority", "Full text"]
COMPARE_FIELDS = ["System", "Method", "Shows", "Does not show", "Open"]
GENERATED = "<!-- Generated by paper-library/scripts/build_index.py from notes/. Do not edit: edit notes/<stem>.md and rebuild. -->"


@dataclass
class Note:
    stem: str
    path: Path
    title: str = ""
    fields: dict = field(default_factory=dict)
    sections: dict = field(default_factory=dict)   # heading -> text
    compare: dict = field(default_factory=dict)

    @property
    def starred(self) -> bool:
        return self.fields.get("Priority", "").strip().lower() == "star"

    @property
    def date(self) -> str:
        return self.fields.get("Date", "").strip()

    @property
    def topic(self) -> str:
        return self.fields.get("Topic", "").strip()


def parse_note(path: Path) -> Note:
    note = Note(stem=path.stem, path=path)
    section = None
    buf: list[str] = []

    def flush():
        if section is not None:
            note.sections[section] = "\n".join(buf).strip()

    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# ") and not note.title and section is None:
            note.title = line[2:].strip()
            continue
        if line.startswith("## "):
            flush()
            section, buf = line[3:].strip(), []
            continue
        if section is None:
            m = FIELD.match(line)
            if m:
                note.fields[m.group(1).strip()] = m.group(2).strip()
        else:
            buf.append(line)
    flush()
    for line in note.sections.get("Compare", "").splitlines():
        m = FIELD.match(line)
        if m:
            note.compare[m.group(1).strip()] = m.group(2).strip()
    return note


@dataclass
class Library:
    root: Path
    name: str = "Paper library"
    recent_from: str = ""
    topics: list = field(default_factory=list)      # (slug, name, covers)
    notes: dict = field(default_factory=dict)       # stem -> Note
    problems: list = field(default_factory=list)

    def topic_name(self, slug: str) -> str:
        for s, n, _ in self.topics:
            if s == slug:
                return n
        return slug


def load_library(root: Path) -> Library:
    root = Path(root)
    lib = Library(root=root)
    cfg = root / "LIBRARY.md"
    if not cfg.exists():
        lib.problems.append(f"missing {cfg}")
    else:
        section = None
        for line in cfg.read_text(encoding="utf-8").splitlines():
            if line.startswith("# ") and section is None:
                lib.name = line[2:].strip()
            elif line.startswith("## "):
                section = line[3:].strip().lower()
            elif FIELD.match(line) and FIELD.match(line).group(1).strip().lower() == "recent from":
                lib.recent_from = FIELD.match(line).group(2).strip()
            elif section == "topics" and line.startswith("|"):
                cells = [c.strip() for c in line.strip().strip("|").split("|")]
                if len(cells) >= 2 and cells[0].lower() != "slug" and not set(cells[0]) <= set("-: "):
                    lib.topics.append((cells[0].strip("`"), cells[1], cells[2] if len(cells) > 2 else ""))
    notes_dir = root / "notes"
    if notes_dir.is_dir():
        for p in sorted(notes_dir.glob("*.md")):
            lib.notes[p.stem] = parse_note(p)
    return lib


def is_recent(lib: Library, note: Note) -> bool:
    if not lib.recent_from or not note.date:
        return True
    # a partial date (YYYY or YYYY-MM) is compared at its own precision
    return note.date >= lib.recent_from[:len(note.date)]


def sort_key(note: Note):
    # starred first, then newest first, then stem
    inv = "".join(chr(255 - ord(c)) for c in note.date.ljust(10, "0"))
    return (0 if note.starred else 1, inv, note.stem)


def oneline(text: str) -> str:
    return re.sub(r"\s+", " ", text or "").strip().replace("|", "\\|")
